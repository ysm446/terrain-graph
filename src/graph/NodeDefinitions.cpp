const char* PinDescription(const Node& node, const Pin& pin) {
    const NodeDefinition* definition = FindNodeDefinition(node.kind);
    if (definition == nullptr) return "";
    // そのノードの入力 / 出力の何番目かで、定義の同じ向きのピンを引く。
    const auto& pins = pin.kind == PinKind::Input ? node.inputs : node.outputs;
    size_t index = 0;
    while (index < pins.size() && pins[index].id != pin.id) ++index;
    for (const PinDefinition& candidate : definition->pins) {
        if (candidate.kind != pin.kind) continue;
        if (index == 0) return candidate.description.Get();
        --index;
    }
    return "";  // 定義に無いピン（Model Merge の増えた入力など）
}

const NodeDefinition* FindNodeDefinition(NodeKind kind) {
    for (const NodeDefinition& definition : kNodeDefinitions) {
        if (definition.kind == kind) {
            return &definition;
        }
    }
    return nullptr;
}

const NodeDefinition* FindNodeDefinitionByName(std::string_view name) {
    for (const NodeDefinition& definition : kNodeDefinitions) {
        if (definition.name == name) {
            return &definition;
        }
    }
    return nullptr;
}

std::optional<size_t> FindPinDefinitionIndex(const NodeDefinition& definition, PinKind kind,
                                             std::string_view name) {
    const auto normalize = [](std::string_view text) {
        std::string result;
        for (const char c : text) {
            if (c == ' ' || c == '_' || c == '-') {
                continue;
            }
            result.push_back((c >= 'A' && c <= 'Z') ? static_cast<char>(c - 'A' + 'a') : c);
        }
        return result;
    };
    const std::string wanted = normalize(name);
    if (wanted.empty()) {
        return std::nullopt;
    }
    size_t index = 0;
    for (const PinDefinition& pin : definition.pins) {
        if (pin.kind != kind) {
            continue;
        }
        if (normalize(pin.label) == wanted) {
            return index;
        }
        ++index;
    }
    return std::nullopt;
}

